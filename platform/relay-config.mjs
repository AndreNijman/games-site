#!/usr/bin/env node
// The one wrangler config every managed relay is deployed with, written from
// the registry (name, domain, what it may bind) and the game's game.yaml (its
// entry point, Durable Objects and migrations). A developer never writes
// wrangler config, so relays cannot drift apart in naming or bindings, and a
// relay cannot bind anything its registry entry does not allow.
//
//   node platform/relay-config.mjs <slug> --manifest <game.yaml> [--out wrangler.platform.jsonc]
import { writeFileSync } from "node:fs";
import { parseArgs } from "node:util";
import { loadPlatform, loadRegistry, PlatformError, readYaml, relayOf, validateGame } from "./lib.mjs";

export function relayConfig(entry, game, platform) {
  const relay = relayOf(entry, platform);
  if (!relay) throw new PlatformError([`registry/${entry.slug}.yaml allows no relay`]);
  if (!game.relay) throw new PlatformError([`${entry.slug}: game.yaml declares no relay`]);
  const r = game.relay;
  const workersDev = entry.relay.workersDev ?? relay.domain === null;
  return {
    name: relay.worker,
    main: r.main,
    compatibility_date: r.compatibilityDate ?? platform.relays.compatibilityDate,
    workers_dev: workersDev,
    preview_urls: false,
    observability: { enabled: true },
    ...(relay.domain ? { routes: [{ pattern: relay.domain, custom_domain: true }] } : {}),
    vars: { ...(r.vars ?? {}), ALLOWED_ORIGINS: `https://${entry.host}` },
    durable_objects: { bindings: r.durableObjects.map((d) => ({ name: d.binding, class_name: d.class })) },
    migrations: r.migrations,
    ...(entry.netlog
      ? { services: [{ binding: "NETLOG", service: platform.cloudflare.netlogService, entrypoint: "NetLog" }] }
      : {}),
  };
}

/** Where the deploy job checks the relay after a deploy. */
export function relayHealthUrl(entry, game, platform) {
  const relay = relayOf(entry, platform);
  const path = game.relay?.health ?? "/health";
  return relay.domain ? `https://${relay.domain}${path}` : null;
}

function main() {
  const { values, positionals } = parseArgs({
    allowPositionals: true,
    options: { manifest: { type: "string" }, out: { type: "string" } },
  });
  const [slug] = positionals;
  if (!slug || !values.manifest) {
    console.error("usage: relay-config.mjs <slug> --manifest <game.yaml> [--out file]");
    process.exit(2);
  }
  try {
    const platform = loadPlatform();
    const entry = loadRegistry(undefined, platform).find((e) => e.slug === slug);
    if (!entry) throw new PlatformError([`${slug} is not registered`]);
    const game = readYaml(values.manifest);
    const problems = validateGame(game, values.manifest);
    if (problems.length) throw new PlatformError(problems);
    const text = `// Generated by platform/relay-config.mjs for ${slug}. Do not edit; change game.yaml or registry/${slug}.yaml.\n${JSON.stringify(relayConfig(entry, game, platform), null, 2)}\n`;
    if (values.out) writeFileSync(values.out, text);
    else process.stdout.write(text);
    const health = relayHealthUrl(entry, game, platform);
    if (health && process.env.GITHUB_OUTPUT) writeFileSync(process.env.GITHUB_OUTPUT, `health=${health}\n`, { flag: "a" });
  } catch (err) {
    if (!(err instanceof PlatformError)) throw err;
    console.error(err.message);
    process.exit(1);
  }
}

if (import.meta.url === `file://${process.argv[1]}`) main();
